// TypeScript renders s as a TypeScript module declaring Methods,
// Publications and Schema, for connect<Schema>() in @cometgo/client. The
// output is sorted by name, so it changes only when the schema does.
func (s *Schema) TypeScript() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by cometgo.Describe; DO NOT EDIT.\n\n")
	b.WriteString("export interface Methods {\n")
	for _, m := range s.Methods {
		fmt.Fprintf(&b, "  %s: {\n    args: %s;\n    result: %s;\n  };\n", tsKey(m.Name), m.Args, m.Result)
	}
	b.WriteString("}\n\nexport interface Publications {\n")
	for _, p := range s.Publications {
		fmt.Fprintf(&b, "  %s: {\n    args: %s;\n    row: %s;\n  };\n", tsKey(p.Name), p.Args, p.rowTS())
	}
	b.WriteString("}\n\nexport interface Schema {\n  methods: Methods;\n  publications: Publications;\n}\n")
	return b.Bytes()
}

func (p *PubSchema) rowTS() string {
	if len(p.Cols) == 0 {
		return "Record<string, never>"
	}
	parts := make([]string, len(p.Cols))
	for i, c := range p.Cols {
		t := codeTS(c.Code, c.Enum)
		if c.Nullable && t != "unknown" {
			t += " | null"
		}
		parts[i] = tsKey(c.Name) + ": " + t
	}
	return "{ " + strings.Join(parts, "; ") + " }"
}

// codeTS is the TypeScript type the client decodes a wire type code to
// (PROTOCOL.md §10, client/src/store.ts decoderFor). An enum with known
// labels becomes their union.
func codeTS(code string, enum []string) string {
	if elem, ok := strings.CutPrefix(code, "[]"); ok {
		return "(" + codeTS(elem, enum) + " | null)[]"
	}
	switch code {
	case "i4", "f8":
		return "number"
	case "bool":
		return "boolean"
	case "tstz":
		return "Date"
	case "bytes":
		return "Uint8Array"
	case "json":
		return "unknown"
	case "enum":
		if len(enum) > 0 {
			labels := make([]string, len(enum))
			for i, l := range enum {
				labels[i] = tsString(l)
			}
			return strings.Join(labels, " | ")
		}
	}
	// i8, num, text, enum, uuid, date, ts, raw.
	return "string"
}

var tsIdent = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func tsKey(name string) string {
	if tsIdent.MatchString(name) {
		return name
	}
	return tsString(name)
}

// tsString quotes s as a JSON string, which is also a valid TS literal.
func tsString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

var (
	jsonMarshaler = reflect.TypeFor[json.Marshaler]()
	textMarshaler = reflect.TypeFor[encoding.TextMarshaler]()
	timeType      = reflect.TypeFor[time.Time]()
	rawType       = reflect.TypeFor[json.RawMessage]()
	numberType    = reflect.TypeFor[json.Number]()
)

func implements(t, iface reflect.Type) bool {
	return t.Implements(iface) || t.Kind() != reflect.Pointer && reflect.PointerTo(t).Implements(iface)
}

// jsonTS is the TypeScript type of t's encoding/json form. Struct fields
// follow encoding/json: json tags rename or drop them, omitempty and
// omitzero make them optional, embedded structs are promoted, and the
// string option turns a number or bool into a string. Values that marshal
// to null (nil pointers, slices, maps, interfaces) include null. A type
// with its own MarshalJSON is unknown, except time.Time (an RFC 3339
// string); one with MarshalText is a string.
func jsonTS(t reflect.Type) string { return (&tsGen{seen: map[reflect.Type]bool{}}).typ(t) }

type tsGen struct{ seen map[reflect.Type]bool }

func (g *tsGen) typ(t reflect.Type) string {
	switch t {
	case timeType:
		return "string"
	case rawType:
		return "unknown"
	case numberType:
		return "number"
	}
	if t.Kind() == reflect.Pointer {
		return nullable(g.typ(t.Elem()))
	}
	if implements(t, jsonMarshaler) {
		return "unknown"
	}
	if implements(t, textMarshaler) {
		return "string"
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.String:
		return "string"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 && !implements(t.Elem(), jsonMarshaler) && !implements(t.Elem(), textMarshaler) {
			return "string | null" // base64
		}
		return nullable(g.array(t.Elem()))
	case reflect.Array:
		return g.array(t.Elem())
	case reflect.Map:
		return nullable("Record<string, " + g.typ(t.Elem()) + ">")
	case reflect.Struct:
		return g.object(t)
	}
	// Interfaces, and kinds encoding/json rejects (chan, func, complex).
	return "unknown"
}

func (g *tsGen) array(elem reflect.Type) string {
	e := g.typ(elem)
	if strings.Contains(e, " ") {
		e = "(" + e + ")"
	}
	return e + "[]"
}

func nullable(t string) string {
	if strings.HasSuffix(t, " | null") || t == "unknown" {
		return t
	}
	return t + " | null"
}

func (g *tsGen) object(t reflect.Type) string {
	if g.seen[t] {
		return "unknown" // recursive type
	}
	g.seen[t] = true
	defer delete(g.seen, t)
	fields := jsonFields(t)
	if len(fields) == 0 {
		return "Record<string, never>"
	}
	parts := make([]string, len(fields))
	for i, f := range fields {
		var ft string
		if f.quoted {
			ft = "string"
			if f.typ.Kind() == reflect.Pointer {
				ft = "string | null"
			}
		} else {
			ft = g.typ(f.typ)
		}
		opt := ""
		if f.optional {
			opt = "?"
		}
		parts[i] = tsKey(f.name) + opt + ": " + ft
	}
	return "{ " + strings.Join(parts, "; ") + " }"
}

type jsonField struct {
	name     string
	typ      reflect.Type
	index    []int
	tagged   bool
	optional bool // omitempty or omitzero
	quoted   bool // ,string on a scalar
}

// jsonFields lists the fields encoding/json encodes for struct type t, in
// its order, applying its rules for embedded structs and name conflicts.
func jsonFields(t reflect.Type) []jsonField {
	type level struct {
		typ   reflect.Type
		index []int
	}
	var fields []jsonField
	visited := map[reflect.Type]bool{}
	next := []level{{typ: t}}
	for len(next) > 0 {
		current := next
		next = nil
		for _, l := range current {
			if visited[l.typ] {
				continue
			}
			visited[l.typ] = true
			for i := range l.typ.NumField() {
				sf := l.typ.Field(i)
				if sf.Anonymous {
					ft := sf.Type
					if ft.Kind() == reflect.Pointer {
						ft = ft.Elem()
					}
					if !sf.IsExported() && ft.Kind() != reflect.Struct {
						continue
					}
				} else if !sf.IsExported() {
					continue
				}
				tag := sf.Tag.Get("json")
				if tag == "-" {
					continue
				}
				name, opts, _ := strings.Cut(tag, ",")
				index := append(slices.Clone(l.index), i)
				ft := sf.Type
				if ft.Name() == "" && ft.Kind() == reflect.Pointer {
					ft = ft.Elem()
				}
				if name != "" || !sf.Anonymous || ft.Kind() != reflect.Struct {
					tagged := name != ""
					if name == "" {
						name = sf.Name
					}
					f := jsonField{name: name, typ: sf.Type, index: index, tagged: tagged}
					for o := range strings.SplitSeq(opts, ",") {
						switch o {
						case "omitempty", "omitzero":
							f.optional = true
						case "string":
							switch ft.Kind() {
							case reflect.Bool, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
								reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
								reflect.Float32, reflect.Float64, reflect.String:
								f.quoted = true
							}
						}
					}
					fields = append(fields, f)
					continue
				}
				next = append(next, level{typ: ft, index: index})
			}
		}
	}
	// Dominant field per name: the shallowest, and among those the only
	// tagged one or the only one; otherwise the name is dropped.
	slices.SortStableFunc(fields, func(a, b jsonField) int {
		if c := strings.Compare(a.name, b.name); c != 0 {
			return c
		}
		if c := len(a.index) - len(b.index); c != 0 {
			return c
		}
		if a.tagged != b.tagged {
			if a.tagged {
				return -1
			}
			return 1
		}
		return slices.Compare(a.index, b.index)
	})
	var out []jsonField
	for i := 0; i < len(fields); {
		j := i + 1
		for j < len(fields) && fields[j].name == fields[i].name {
			j++
		}
		group := fields[i:j]
		i = j
		if len(group) > 1 && len(group[1].index) == len(group[0].index) && group[1].tagged == group[0].tagged {
			continue
		}
		out = append(out, group[0])
	}
	slices.SortFunc(out, func(a, b jsonField) int { return slices.Compare(a.index, b.index) })
	return out
}

// rowCols describes the columns of Row struct type t for PubOptions.Row:
// the column name is the json tag or field name, the code follows the Go
// type the column would scan into, and pointer fields are nullable.
func rowCols(t reflect.Type) ([]ColSchema, error) {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return nil, fmt.Errorf("Row must be a struct, not %s", t)
	}
	var cols []ColSchema
	for _, f := range jsonFields(t) {
		ft := f.typ
		c := ColSchema{Name: f.name}
		if ft.Kind() == reflect.Pointer {
			c.Nullable = true
			ft = ft.Elem()
		}
		code, err := goCode(ft)
		if err != nil {
			return nil, fmt.Errorf("Row field %s: %w", f.name, err)
		}
		c.Code = code
		cols = append(cols, c)
	}
	return cols, nil
}

func goCode(t reflect.Type) (string, error) {
	switch t {
	case timeType:
		return "tstz", nil
	case rawType:
		return "json", nil
	}
	switch t.Kind() {
	case reflect.Bool:
		return "bool", nil
	case reflect.Int8, reflect.Int16, reflect.Int32, reflect.Uint8, reflect.Uint16:
		return "i4", nil
	case reflect.Int, reflect.Int64, reflect.Uint32, reflect.Uint, reflect.Uint64:
		return "i8", nil
	case reflect.Float32, reflect.Float64:
		return "f8", nil
	case reflect.String:
		return "text", nil
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return "bytes", nil
		}
		elem, err := goCode(t.Elem())
		if err != nil {
			return "", err
		}
		return "[]" + elem, nil
	case reflect.Map, reflect.Struct, reflect.Interface:
		return "json", nil
	}
	return "", fmt.Errorf("no column type for %s", t)
}

// argsTS is jsonTS for a method's or publication's args. Empty args
// (struct{}) also accept null, so the client may omit them.
func argsTS(t reflect.Type) string {
	ts := jsonTS(t)
	if ts == "Record<string, never>" {
		return ts + " | null"
	}
	return ts
}
